/**
 * Features page — AI Market Brief.
 *
 * Auto-loads a Gemini insight for every market (backend caches per market for
 * ~5 minutes). Fallback insights render as calm copy, never error banners.
 */

import { Link } from "react-router-dom";

import MiniPriceChart from "../components/market/MiniPriceChart";
import { useMarketBrief } from "../hooks/useMarketBrief";
import { MarketBriefItem } from "../lib/api";
import { CONFIDENCE_LABELS, TREND_LABELS } from "../lib/insightFormat";
import { formatPercentFromBps, formatPriceFromBps } from "../lib/marketFormat";
import { OUTCOME } from "../lib/terminology";

function BriefSkeleton() {
  return (
    <div className="animate-pulse rounded-card border border-line bg-card p-6">
      <div className="h-3 w-16 rounded-full bg-line" />
      <div className="mt-3 h-4 w-3/4 rounded bg-line" />
      <div className="mt-4 h-3 w-full rounded bg-line" />
      <div className="mt-2 h-3 w-5/6 rounded bg-line" />
    </div>
  );
}

function BriefCard({ item }: { item: MarketBriefItem }) {
  const trend = TREND_LABELS[item.insight.trend];

  return (
    <article className="flex flex-col gap-3 rounded-card border border-line bg-card p-6">
      <div className="flex items-center justify-between gap-2 text-xs">
        <span className="rounded-full border border-line px-2 py-0.5 text-muted">
          {item.category}
        </span>
        <span className="font-data tabular-nums text-ink">
          {formatPriceFromBps(item.yes_price_bps)}{" "}
          <span className="text-muted">
            ({formatPercentFromBps(item.yes_price_bps)} {OUTCOME.yes.label})
          </span>
        </span>
      </div>

      <h2 className="font-display text-lg font-semibold text-ink">
        <Link
          to={`/markets/${item.market_id}`}
          className="hover:underline focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-gold"
        >
          {item.market_title}
        </Link>
      </h2>

      <div>
        <MiniPriceChart
          priceSeries={item.price_series}
          currentYesPriceBps={item.yes_price_bps}
        />
        <p className="mt-1 text-right font-data text-xs tabular-nums text-muted">
          {item.price_series.length > 0
            ? `${item.price_series.length} trade${item.price_series.length === 1 ? "" : "s"}`
            : "Awaiting first trade"}
        </p>
      </div>

      <div className="flex flex-wrap items-center gap-2 text-xs">
        <span
          className={`rounded-full border border-line px-2 py-0.5 ${trend.className}`}
        >
          {trend.label}
        </span>
        <span className="rounded-full border border-line px-2 py-0.5 text-muted">
          {CONFIDENCE_LABELS[item.insight.confidence]}
        </span>
      </div>

      <p className="text-sm text-ink">{item.insight.summary}</p>
      <p className="text-sm text-muted">{item.insight.key_observation}</p>

      {item.source === "fallback" && (
        <p className="text-xs text-muted">
          Waiting on more trades for a live read — this is a general note.
        </p>
      )}
    </article>
  );
}

export default function Features() {
  const { status, data, refresh } = useMarketBrief();
  const items = data?.markets ?? [];

  return (
    <main className="mx-auto max-w-6xl px-4 py-10">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <p className="font-display text-sm font-medium uppercase tracking-[0.12em] text-gold-ink">
            Features
          </p>
          <h1 className="mt-2 font-display text-3xl font-semibold text-ink">
            AI Market Brief
          </h1>
          <p className="mt-2 max-w-2xl text-base text-muted">
            A plain-English read of recent price action on every market,
            generated by Gemini from live trade data.
          </p>
        </div>
        <button
          type="button"
          onClick={() => void refresh()}
          disabled={status === "loading"}
          className="rounded-btn border border-line bg-card px-4 py-2 text-sm text-ink hover:border-gold focus-visible:outline focus-visible:outline-2 focus-visible:outline-gold disabled:opacity-50"
        >
          Refresh brief
        </button>
      </div>

      {status === "loading" && items.length === 0 && (
        <div
          className="mt-10 grid gap-6 md:grid-cols-2 lg:grid-cols-3"
          role="status"
          aria-label="Loading AI market brief"
        >
          <BriefSkeleton />
          <BriefSkeleton />
          <BriefSkeleton />
        </div>
      )}

      {status === "error" && (
        <div className="mt-10 rounded-card border border-line bg-card p-6">
          <p className="text-sm text-muted">
            Couldn&apos;t load the brief right now. The markets themselves are
            unaffected — try again in a moment.
          </p>
          <button
            type="button"
            onClick={() => void refresh()}
            className="mt-3 rounded-btn bg-deck px-4 py-2 text-sm font-medium text-card"
          >
            Try again
          </button>
        </div>
      )}

      {status === "success" && items.length === 0 && (
        <p className="mt-10 text-sm text-muted">
          No markets yet. Run the backend seed to load demo markets.
        </p>
      )}

      {items.length > 0 && (
        <div className="mt-10 grid gap-6 md:grid-cols-2 lg:grid-cols-3">
          {items.map((item) => (
            <BriefCard key={item.market_id} item={item} />
          ))}
        </div>
      )}
    </main>
  );
}
